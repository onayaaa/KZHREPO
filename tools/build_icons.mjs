// Regenerates site/assets/js/icons.js from the Reicon icon set.
// Reicon: https://reicon.dev  (npm package: reicon@1.2.5, MIT)
//
// Usage:  node tools/build_icons.mjs
//
// Each Reicon module carries its SVG preview as a base64 data URL inside the
// JSDoc header, so we can extract the exact geometry without parsing JS.

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const NAMES = [
  'Search', 'X', 'ChevronDown', 'ArrowUpRight', 'Play', 'Calendar',
  'Clock', 'Users', 'Trophy', 'Music', 'Gamepad', 'Filter', 'Minus', 'Menu',
];

const BASE = 'https://cdn.jsdelivr.net/npm/reicon@1.2.5/icons/';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'site', 'assets', 'js', 'icons.js');

const key = (name) => name
  .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
  .toLowerCase();

function extract(svg) {
  const vb = (svg.match(/viewBox="([^"]+)"/) || [])[1];
  if (!vb) throw new Error('no viewBox');
  const body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/#e4e4e7/gi, 'currentColor')
    .replace(/#E4E4E7/gi, 'currentColor')
    .replace(/\s+/g, ' ')
    .trim();
  return { vb, body };
}

async function fetchIcon(name) {
  const res = await fetch(BASE + name + '.js');
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  const src = await res.text();
  const m = src.match(/data:image\/svg\+xml;base64,([A-Za-z0-9+/=]+)/);
  if (!m) throw new Error(`${name}: no preview payload`);
  const svg = Buffer.from(m[1], 'base64').toString('utf8');
  return extract(svg);
}

const data = {};
for (const name of NAMES) {
  data[key(name)] = await fetchIcon(name);
  process.stdout.write(`ok ${key(name)}\n`);
}

const lines = [];
lines.push('/* Generated by tools/build_icons.mjs — do not edit by hand.');
lines.push('   Geometry: Reicon 1.2.5 (MIT) — https://reicon.dev/icons */');
lines.push('window.KZ_ICON_DATA = {');
for (const [k, v] of Object.entries(data)) {
  lines.push(`  "${k}": { vb: "${v.vb}", body: ${JSON.stringify(v.body)} },`);
}
lines.push('};');
lines.push('');
lines.push('window.KZIcon = function (name, cls) {');
lines.push('  var d = window.KZ_ICON_DATA[name];');
lines.push('  if (!d) return "";');
lines.push('  return \'<svg class="icon\' + (cls ? " " + cls : "") + \'" viewBox="\' + d.vb + \'" fill="currentColor" aria-hidden="true" focusable="false">\' + d.body + "</svg>";');
lines.push('};');
lines.push('');

await writeFile(OUT, lines.join('\n'), 'utf8');
console.log('wrote', path.relative(ROOT, OUT), `(${Object.keys(data).length} icons)`);
